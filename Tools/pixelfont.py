# Glif basina ilerleme genisligi. Belirtilmeyen 5+1=6 kullanir.
#
# Orantili genislik: sabit genislik pixel art'ta "daktilo" gorunumu veriyor
# ve kelimeler seyreliyor.
ADVANCE: dict[str, int] = {
    " ": 4,
    "i": 3, "ı": 3, "l": 3, "j": 4, "I": 5, "İ": 5,
    ".": 3, ",": 3, ":": 3, ";": 3, "!": 3, "'": 2, "|": 3,
    "(": 4, ")": 4, "[": 4, "]": 4, "{": 4, "}": 4,
    "t": 5, "f": 5, "r": 5,
    "m": 6, "w": 6, "M": 6, "W": 6,
}

DEFAULT_ADVANCE = 6


def glyph_rows(ch: str) -> list[str]:
    """Karakterin cizim satirlari; tanimsizsa bos kutu (.notdef)."""
    if ch in GLYPHS:
        return GLYPHS[ch]

    # Tanimsiz karakter GORUNUR olmali: sessizce bosluk cizmek, eksik
    # glifin fark edilmemesine yol acar.
    return ["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"]


def advance_of(ch: str) -> int:
    """Bir sonraki karaktere kadarki yatay ilerleme."""
    return ADVANCE.get(ch, DEFAULT_ADVANCE)


def charset() -> list[str]:
    """Atlasa girecek karakterler: yazdirilabilir ASCII + Turkce."""
    ascii_chars = [chr(c) for c in range(32, 127)]
    turkish = ["Ç", "Ğ", "İ", "Ö", "Ş", "Ü", "ç", "ğ", "ı", "ö", "ş", "ü"]

    # Tekrar olmasin: Turkce harflerin hicbiri ASCII'de yok ama liste
    # elle duzenlenirse kazara cakisabilir.
    return ascii_chars + [c for c in turkish if c not in ascii_chars]
