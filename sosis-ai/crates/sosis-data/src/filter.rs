//! Kalite filtreleri ve tekilleştirme (dedup).

use std::collections::hash_map::DefaultHasher;
use std::hash::{Hash, Hasher};

/// Belgenin neden elendiği.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Reject {
    TooShort,
    TooLong,
    Minified,
    Generated,
    LowAlnum,
}

pub struct FilterOptions {
    pub min_chars: usize,
    pub max_chars: usize,
    pub max_line_len: usize,
    pub max_avg_line_len: f32,
    pub min_alnum_frac: f32,
}

impl Default for FilterOptions {
    fn default() -> Self {
        Self {
            min_chars: 64,
            max_chars: 500_000,
            max_line_len: 1000,
            max_avg_line_len: 120.0,
            min_alnum_frac: 0.25,
        }
    }
}

const GENERATED_MARKERS: &[&str] = &[
    "auto-generated",
    "autogenerated",
    "do not edit",
    "generated by",
    "<auto-generated",
    "@generated",
];

/// Belgeyi kalite kurallarına göre kontrol eder.
pub fn check(text: &str, o: &FilterOptions) -> Result<(), Reject> {
    if text.len() < o.min_chars {
        return Err(Reject::TooShort);
    }
    if text.len() > o.max_chars {
        return Err(Reject::TooLong);
    }
    let mut lines = 0usize;
    let mut max_line = 0usize;
    for l in text.lines() {
        lines += 1;
        max_line = max_line.max(l.len());
    }
    let avg = text.len() as f32 / lines.max(1) as f32;
    if max_line > o.max_line_len || avg > o.max_avg_line_len {
        return Err(Reject::Minified);
    }
    let head: String = text
        .lines()
        .take(5)
        .collect::<Vec<_>>()
        .join("\n")
        .to_lowercase();
    if GENERATED_MARKERS.iter().any(|m| head.contains(m)) {
        return Err(Reject::Generated);
    }
    let alnum = text.chars().filter(|c| c.is_alphanumeric()).count();
    if (alnum as f32) < o.min_alnum_frac * text.chars().count() as f32 {
        return Err(Reject::LowAlnum);
    }
    Ok(())
}

/// Boşluklardan bağımsız içerik özeti; birebir kopyaları yakalamak için.
pub fn content_hash(text: &str) -> u64 {
    let mut h = DefaultHasher::new();
    for tok in text.split_whitespace() {
        tok.hash(&mut h);
    }
    h.finish()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn filters() {
        let o = FilterOptions::default();
        let good = "fn main() {\n    println!(\"merhaba dünya\");\n}\n".repeat(4);
        assert_eq!(check(&good, &o), Ok(()));
        assert_eq!(check("x", &o), Err(Reject::TooShort));
        let minified = format!("var a={};", "b".repeat(2000));
        assert_eq!(check(&minified, &o), Err(Reject::Minified));
        let generated = format!("// <auto-generated>\n{good}");
        assert_eq!(check(&generated, &o), Err(Reject::Generated));
    }

    #[test]
    fn dedup_ignores_whitespace() {
        assert_eq!(content_hash("fn a() {}\n"), content_hash("fn  a()   {}"));
        assert_ne!(content_hash("fn a() {}"), content_hash("fn b() {}"));
    }
}
