def _ninepatch(w: int, h: int, fill: str, border: str, light: str | None, dark: str | None,
               radius: int = 2) -> Image.Image:
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle([0, 0, w - 1, h - 1], radius=radius, fill=hex_rgba(border))
    d.rounded_rectangle([1, 1, w - 2, h - 2], radius=max(0, radius - 1), fill=hex_rgba(fill))
    if light:
        d.line([2, 1, w - 3, 1], fill=hex_rgba(light))
    if dark:
        d.line([2, h - 2, w - 3, h - 2], fill=hex_rgba(dark))
    return img


