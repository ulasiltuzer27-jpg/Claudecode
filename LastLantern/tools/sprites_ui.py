def build() -> None:
    for name, rows in ICONS.items():
        w = max(len(r) for r in rows)
        img = grid(rows, size=(w, len(rows)))
        if name[0] in "wep" and name[1] == "_":
            canvas = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
            canvas.alpha_composite(img, ((16 - img.width) // 2 + 1, (16 - img.height) // 2))
            img = canvas
        save(outline(img), f"icon_{name}")
    frames()


if __name__ == "__main__":
    build()
