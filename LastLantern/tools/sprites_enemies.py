def _eyes(img_rows: list[str], pal: dict[str, str], size) -> Image.Image:
    """Yalnizca goz piksellerini birakan maske: karanlikta parlayan gozler."""
    rows = ["".join(ch if ch == "e" else "." for ch in r) for r in img_rows]
    return grid(rows, {"e": "#FFFFFF"}, size=size)


def _build(table: dict[str, dict], prefix: str) -> None:
    for name, spec in table.items():
        frames = spec["frames"]
        w = max(len(r) for r in frames[0])
        h = len(frames[0])
        imgs = [outline(grid(f, spec["pal"], size=(w, h))) for f in frames]
        save_frames(imgs, f"{prefix}{name}")
        save(_eyes(frames[0], spec["pal"], (w, h)), f"{prefix}{name}_eyes")


def build() -> None:
    _build(ENEMIES, "enemy_")
    _build(MINIBOSSES, "miniboss_")
    _build(BOSSES, "boss_")


if __name__ == "__main__":
    build()
